# Rows look like:  | Briefing -- read this first | `_READ-FIRST-...md` | 0 |
$rowPat = '^\|\s*(.+?)\s*\|\s*' + $bt + '(.+?)' + $bt + '\s*\|\s*(\d+)\s*\|'
$namedCurrent = @{}      # label -> filename
$namedOlder   = @{}      # label -> count of older versions CURRENT.md admits to
foreach ($line in (Get-Content -LiteralPath $currentMd -Encoding UTF8)) {
    $m = [regex]::Match($line, $rowPat)
    if ($m.Success -and $m.Groups[1].Value -ne "What it is") {
        $namedCurrent[$m.Groups[1].Value] = $m.Groups[2].Value
        $namedOlder[$m.Groups[1].Value]   = [int]$m.Groups[3].Value
    }
}

# The documents that speak in the PRESENT TENSE about NOW. A dated record --
# a session log, a test history, a field plan -- is allowed to carry an old
