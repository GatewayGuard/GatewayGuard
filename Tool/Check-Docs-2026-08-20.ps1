W "-- 4. ONE LIVE COPY, OR CURRENT.md NAMES WHICH ONE -------------------"
W "  Several copies are fine as long as something says which is live. What is"
W "  not fine is three drafts and nothing to choose between them."
W ""

$fam = @{}
foreach ($f in (Get-ChildItem -LiteralPath $docs -Filter "*.md" -File)) {
    $m = [regex]::Match($f.Name, '^(.*?)-(\d{4}-\d{2}-\d{2}(?:-\d{3,4})?)(.*)$')
    if (-not $m.Success) { continue }
    $key = $m.Groups[1].Value + $m.Groups[3].Value
    if (-not $fam.ContainsKey($key)) { $fam[$key] = New-Object System.Collections.ArrayList }
    [void]$fam[$key].Add($f.Name)
}

$namedFiles = New-Object 'System.Collections.Generic.HashSet[string]'
foreach ($v in $namedCurrent.Values) { [void]$namedFiles.Add((Split-Path ($v -replace '\\','/') -Leaf)) }

$unresolved = 0
foreach ($k in ($fam.Keys | Sort-Object)) {
    if ($fam[$k].Count -lt 2) { continue }
    $isNamed = $false
    foreach ($n in $fam[$k]) { if ($namedFiles.Contains($n)) { $isNamed = $true } }
    if ($isNamed) {
        W ("      OK        " + $k + "  -- " + $fam[$k].Count + " copies, CURRENT.md names the live one")
    } else {
        $unresolved++
        W ("      NO ANCHOR " + $k + "  -- " + $fam[$k].Count + " copies, nothing says which:")
        foreach ($n in ($fam[$k] | Sort-Object)) { W ("                    " + $n) }
    }
}
W ("  families with copies and no anchor : " + $unresolved + "   (baseline " + $BASE_UNRESOLVED_FAMILIES + ")")
if ($unresolved -gt $BASE_UNRESOLVED_FAMILIES) {
    $problems++
    W "  RESULT: FAIL -- add a row to Update-Current.ps1, or retire the old copies."
} elseif ($unresolved -lt $BASE_UNRESOLVED_FAMILIES) {
    W ("  RESULT: improved. Lower the baseline in this script to " + $unresolved + ".")
} else {
    W "  RESULT: holding at the baseline. Carried, not passed."
}
W ""

# ====================================================================
#  5. THE CONTENT STAMP
# ====================================================================
W "-- 5. THE CONTENT STAMP ----------------------------------------------"
W "  SyncPlan 6c, last item: the stamp should carry a hash of the file's own"
W "  content. Without one, two files with the same Dated: line and different"
W "  text read as identical -- which is exactly what a mid-session edit makes."
W "  SyncPlan records the hash as ASPIRATIONAL, not built. This section"
W "  verifies any stamp that IS there and counts the rest. It does not invent"
W "  a number and call it adopted."
W ""

$withHash = 0; $hashOK = 0; $hashBad = 0
foreach ($f in $factFiles) {
    $lines = [System.IO.File]::ReadAllLines($f)
    $hm = $null
    foreach ($ln in ($lines | Select-Object -First 6)) {
        $x = [regex]::Match($ln, 'Content-SHA256:\s*([0-9a-fA-F]{8,64})')
        if ($x.Success) { $hm = $x; break }
    }
    if (-not $hm) { continue }
    $withHash++
    # Hash the file with its own stamp line blanked, so the stamp can describe
    # the file it lives in without chasing its own tail.
    $body = ($lines | Where-Object { $_ -notmatch 'Content-SHA256:' }) -join "`n"
    $sha  = [System.BitConverter]::ToString(
                (New-Object System.Security.Cryptography.SHA256Managed).ComputeHash(
                    [System.Text.Encoding]::UTF8.GetBytes($body))).Replace("-", "").ToLower()
    if ($sha.StartsWith($hm.Groups[1].Value.ToLower())) {
        $hashOK++
        W ("      OK   " + (Split-Path $f -Leaf))
    } else {
        $hashBad++
        $problems++
        W ("      EDITED SINCE STAMPING  " + (Split-Path $f -Leaf))
        W ("           stamp says " + $hm.Groups[1].Value + ", content is " + $sha.Substring(0, 16))
    }
}
W ("  live documents carrying a content hash : " + $withHash + " of " + $factFiles.Count)
if ($withHash -eq 0) {
    W "  RESULT: not adopted yet. This is SyncPlan 6c's open item, unchanged."
    W "          To adopt: add a line to each live document reading"
    W "          Content-SHA256: <first 16 hex of the SHA-256 of the file with"
    W "          that line removed>, and this section starts enforcing it."
} elseif ($hashBad -eq 0) {
    W "  RESULT: every stamp present matches its file."
} else {
    W ("  RESULT: FAIL -- " + $hashBad + " document(s) changed after being stamped.")
}
W ""

