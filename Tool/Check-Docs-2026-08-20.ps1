W ""

# ====================================================================
#  1. NO TWO DOCUMENTS STATE THE SAME VOLATILE FACT
# ====================================================================
W "-- 1. VOLATILE FACTS -- STATED ONCE, AND TRUE ------------------------"
W "  Section 7b: a fact stated once can be wrong. A fact stated twice can be"
W "  INCONSISTENT, and then nobody knows which to believe. So each fact below"
W "  is counted across the live documents AND checked against the machine."
W ""

# A sentence that QUOTES a wrong old figure in order to correct it is not a
# competing claim -- it is the record of the correction. The briefing's own
# change history opens with *said "Active build: ascii39"*, and counting that
# as a live claim would make this gate report the very fix that closed it.
$notAClaim = '\bsaid\b|[Ss]upersede|[Ss]uperseded|used to|formerly|it had|stale|' +
             'was\s+\*?\*?ascii|previously'

function Get-Fact([string]$path, [string]$pattern) {
    # Returns every captured value of $pattern in $path, with its line number.
    $hits = New-Object System.Collections.ArrayList
    $n = 0
    foreach ($line in (Get-Content -LiteralPath $path -Encoding UTF8)) {
        $n++
        if ($line -match $notAClaim) { continue }
        foreach ($m in [regex]::Matches($line, $pattern)) {
            [void]$hits.Add(@{ value = $m.Groups[1].Value; line = $n })
        }
    }
    return $hits
}

# Documents write a figure the way a human reads it -- "8,921", "ascii42".
# The machine returns "8921" and "42". Compare the numbers, not the decoration.
function Get-Normal([string]$v) {
    return ($v -replace ',', '' -replace '(?i)^ascii', '').Trim()
}

function Test-Fact([string]$name, [string]$pattern, [string]$measured, [string]$note) {
    $stated = New-Object System.Collections.ArrayList
    foreach ($f in $factFiles) {
        foreach ($h in (Get-Fact $f $pattern)) {
            [void]$stated.Add(@{ file = (Split-Path $f -Leaf); line = $h.line; value = $h.value })
        }
    }
    W ("  " + $name)
    if ($stated.Count -eq 0) {
        W ("      stated in no live document. measured: " + $measured)
        W ""
        return 0
    }
    $values = @($stated | ForEach-Object { Get-Normal $_.value } | Sort-Object -Unique)
    foreach ($s in $stated) {
        W ("      " + $s.file + ":" + $s.line + "  says " + $s.value)
    }
    W ("      measured now : " + $measured)
    $bad = 0
    if ($values.Count -gt 1) {
        W "      DISAGREE -- the live documents do not tell the same story."
        $bad = 1
    }
    if ($values -notcontains (Get-Normal $measured)) {
        W "      STALE -- what the documents say is not what the machine says."
        W ("      " + $note)
        $bad = 1
    }
    if ($bad -eq 0) { W "      OK -- agrees with itself and with the machine." }
    W ""
    return $bad
}

# --- measure the machine ------------------------------------------------
# VERIFIED 2026-08-20 measured on CGDELL: the newest build on disk is
