# VERIFIED 2026-08-20 measured on CGDELL: "git rev-list --count HEAD" prints
# a bare integer; "git ls-files" one path per line; "git rev-list --count
# origin/main..HEAD" the number of commits GitHub has not got yet.
$mCommits  = "" + (& git rev-list --count HEAD 2>$null)
$mTracked  = "" + (@(& git ls-files 2>$null)).Count
$mUnpushed = "" + (& git rev-list --count origin/main..HEAD 2>$null)

# EVERY PATTERN BELOW MATCHES A DECLARATION, NEVER A MENTION. The first
# version of this gate matched any "asciiNN" and reported seventeen claims
# about the current build, sixteen of which were ordinary prose about older
# ones -- counting a proxy instead of the thing, which is the failure the
# project instructions name in so many words. "Active build:" and "Current
# build:" are the two forms the live documents actually use; a build number
# in a sentence is history and is left alone.
$problems += Test-Fact "ACTIVE BUILD NUMBER" '(?:Active build|Current build)[^\r\n]{0,8}?ascii(\d+)' $mBuild `
    "Update CLAUDE.md line 9 and briefing section 1 in the same edit as the build."
$problems += Test-Fact "BUILD SIZE -- non-blank lines" '\*?\*?([\d,]{4,7})\*?\*? non-blank' $mNonBlank `
    "Appendix A method: Measure-Object -Line on the non-blank count."
# "lines / N total" is the live form. The Playbook's "non-blank lines (5,900
# total)" is a defect write-up about a file that no longer exists, so the
