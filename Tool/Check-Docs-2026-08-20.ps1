$problems += Test-Fact "TRACKED FILES" '\|\s*Tracked files\s*\|\s*\*?\*?([\d,]+)' $mTracked `
    "Take it three ways -- ls-files, ls-files -z, ls-tree -r HEAD -- and say so."
$problems += Test-Fact "UNPUSHED COMMITS" '\|\s*Unpushed\s*\|\s*\*?\*?([\d,]+)' $mUnpushed `
    "Push, then re-measure. A stale zero here is the worst line in the document."

# ====================================================================
#  2. DEAD POINTERS
# ====================================================================
W "-- 2. DEAD POINTERS --------------------------------------------------"
W "  A pointer that lies is worse than no pointer. Every dated filename in"
W "  backticks must exist somewhere in the tree."
W ""

# Every filename on disk, once.
$onDisk = New-Object 'System.Collections.Generic.HashSet[string]'
foreach ($f in (Get-ChildItem -LiteralPath $repo -Recurse -File -Force -ErrorAction SilentlyContinue)) {
    if ($f.FullName -like "*\.git\*") { continue }
    [void]$onDisk.Add($f.Name)
}

$ptrPat = $bt + '([^' + $bt + ']*\d{4}-\d{2}-\d{2}[^' + $bt + ']*?\.(?:md|ps1|bat|py|txt|docx|pdf|pptx))' + $bt

# A NAME IS NOT ALWAYS A POINTER. 6c says "referenced in a pointer context",
# and it was right to. These three contexts name a file in order to say it is
# GONE, so finding it absent is the sentence working, not failing.
$notPointer = '[Ss]upersede|[Ss]uperseded|[Rr]etired|[Rr]eplaced by|no longer|was renamed|' +
              'Older versions|older version|previous version|[Dd]eleted|[Rr]emoved|used to be'

function Get-DeadPointers([string]$path) {
    $out = New-Object System.Collections.ArrayList
    $n = 0
    foreach ($line in (Get-Content -LiteralPath $path -Encoding UTF8)) {
        $n++
        if ($line -match $notPointer) { continue }
        foreach ($m in [regex]::Matches($line, $ptrPat)) {
            $raw = $m.Groups[1].Value
            # An elided name -- "W11-...ascii33-2026-07-19.ps1" -- is prose, not a path.
            if ($raw -match '\.\.\.' -or $raw -match '\*') { continue }
            $base = Split-Path ($raw -replace '\\', '/') -Leaf
            if (-not $onDisk.Contains($base)) {
                [void]$out.Add(@{ line = $n; name = $base })
            }
        }
    }
    return $out
}

$deadGov = 0
foreach ($f in $factFiles) {
    foreach ($d in (Get-DeadPointers $f)) {
        $deadGov++
        W ("      " + (Split-Path $f -Leaf) + ":" + $d.line + "  -> " + $d.name)
    }
}
W ("  dead pointers in the live documents : " + $deadGov + "   (baseline " + $BASE_DEAD_POINTERS_GOVERNING + ")")

$deadAll = 0
foreach ($f in (Get-ChildItem -LiteralPath $docs -Filter "*.md" -File)) {
    $deadAll += (Get-DeadPointers $f.FullName).Count
}
W ("  dead pointers across all ProjectDocs : " + $deadAll + "   (baseline " + $BASE_DEAD_POINTERS_ALL + ")")

if ($deadGov -gt $BASE_DEAD_POINTERS_GOVERNING -or $deadAll -gt $BASE_DEAD_POINTERS_ALL) {
    $problems++
    W "  RESULT: FAIL -- a NEW dead pointer appeared. Fix it, do not raise the baseline."
} elseif ($deadGov -lt $BASE_DEAD_POINTERS_GOVERNING -or $deadAll -lt $BASE_DEAD_POINTERS_ALL) {
    W ("  RESULT: improved. Lower the baselines in this script to " + $deadGov + " and " + $deadAll + ".")
} else {
    W "  RESULT: holding at the baseline. Carried, not passed."
}
W ""

# ====================================================================
#  3. THE Dated: HEADER MATCHES THE FILENAME
# ====================================================================
W "-- 3. FILENAME DATE vs INTERNAL Dated: -------------------------------"
W "  Naming standard: the two are updated in the same edit, never one alone."
W ""

$mismatch = 0
$noStamp  = 0
foreach ($f in (Get-ChildItem -LiteralPath $docs -Filter "*.md" -File)) {
    # Generated twins carry the GENERATION time, not the source's date. That is
    # correct behaviour for build_readable_twins.py, so they are out of scope.
    if ($f.Name -like "*-TEXT.md") { continue }
    if ($f.Name -eq "CURRENT.md")  { continue }   # generated; carries Generated:, not Dated:

    $fm = [regex]::Match($f.Name, '(\d{4}-\d{2}-\d{2})(?:-(\d{2})(\d{2}))?')
    if (-not $fm.Success) { continue }            # no date in the name, nothing to compare

    $head = (Get-Content -LiteralPath $f.FullName -TotalCount 6 -Encoding UTF8) -join "`n"
    $hm = [regex]::Match($head, 'Dated:\s*(\d{4}-\d{2}-\d{2})(?:\s+(\d{2}):(\d{2}))?')
    if (-not $hm.Success) { $noStamp++; continue }

    $bad = $false
    if ($hm.Groups[1].Value -ne $fm.Groups[1].Value) { $bad = $true }
    if ($fm.Groups[2].Success -and $hm.Groups[2].Success) {
        if ($fm.Groups[2].Value -ne $hm.Groups[2].Value -or $fm.Groups[3].Value -ne $hm.Groups[3].Value) { $bad = $true }
    }
    if ($bad) {
        $mismatch++
        W ("      " + $f.Name + "  header says " + $hm.Groups[0].Value)
    }
}
W ("  documents whose header disagrees with their name : " + $mismatch + "   (baseline " + $BASE_DATE_MISMATCH + ")")
W ("  documents carrying no Dated: header at all       : " + $noStamp + "   (reported, not failed)")
if ($mismatch -gt $BASE_DATE_MISMATCH) {
    $problems++
    W "  RESULT: FAIL -- fix the header, or rename the file. Same edit, both."
} else {
    W "  RESULT: clear."
}
W ""

# ====================================================================
#  4. ONE LIVE COPY OF EACH DOCUMENT FAMILY
