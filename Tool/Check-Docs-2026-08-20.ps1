W "  Sections 2 and 4 report at their baseline rather than failing, because"
W "  the exceptions predate the gate. Section 1 fails on sight -- it is small,"
W "  it is exact, and it is where the briefing went three builds stale."

Set-Content -LiteralPath $outFile -Value ($L -join "`r`n") -Encoding UTF8
Write-Host ""
Write-Host ("  Saved to: " + $outFile) -ForegroundColor Green
Write-Host ""
